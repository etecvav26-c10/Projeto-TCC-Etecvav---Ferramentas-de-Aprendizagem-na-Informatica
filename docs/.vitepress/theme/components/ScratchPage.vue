<script setup>
import { ref, onMounted } from 'vue'

const stats = ref({
  projects: '0',
  users: '0',
  studios: '0'
})

function animateCount(refKey, target, suffix = '') {
  const duration = 2000
  const steps = 60
  const increment = target / steps
  let current = 0
  const interval = setInterval(() => {
    current += increment
    if (current >= target) {
      stats.value[refKey] = target.toLocaleString('pt-BR') + suffix
      clearInterval(interval)
    } else {
      stats.value[refKey] = Math.floor(current).toLocaleString('pt-BR') + suffix
    }
  }, duration / steps)
}

onMounted(() => {
  animateCount('projects', 130000000, '+')
  animateCount('users', 100000000, '+')
  animateCount('studios', 50000000, '+')
})
</script>

